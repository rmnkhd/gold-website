import { formatPrice } from '../utils/number.ts';
import { jalaliLabel } from './jalali-label.ts';
import { changeSentence, type HistorySummary } from './price-history.ts';

export interface Faq {
    q: string;
    a: string;
}

export interface FaqContext {
    /** مثلاً «طلای ۱۸ عیار» */
    title: string;
    /** «هر گرم» | «هر سکه» | «هر اونس» */
    unit: string;
    /** «تومان» | «دلار» */
    currency: string;
    /** قیمت زنده‌ی تأییدشده؛ نبود = عدد «امروز» ساخته نمی‌شود */
    livePrice: number | undefined;
    summary: HistorySummary;
    /** مثلاً «۳۰ روز» */
    spanLabel: string;
    /** اولین روز ثبت‌شده‌ی تاریخچه (ISO)؛ خالی = هنوز نیست */
    sinceIso: string | undefined;
}

/**
 * پرسش‌های متداول با پاسخ ساخته‌شده از داده‌ی همان روز (به‌روز می‌ماند و در JSON-LD هم می‌آید).
 * عدد «امروز» فقط از قیمت زنده‌ی تأییدشده؛ هیچ پیش‌بینی‌ای ساخته نمی‌شود.
 */
export function buildPriceFaq(c: FaqContext): Faq[] {
    const s = c.summary;
    const hasData = s.days >= 2;
    const money = (v: number): string => `${formatPrice(v)} ${c.currency}`;
    const today =
        c.livePrice !== undefined
            ? `قیمت ${c.title} ${c.unit} هم‌اکنون ${money(c.livePrice)} است (قیمت زنده‌ی تأییدشده؛ زمان به‌روزرسانی در بالای صفحه دیده می‌شود).`
            : `قیمت زنده‌ی ${c.title} در این لحظه به‌روز نیست؛ آخرین قیمت‌های ثبت‌شده را در جدول و نمودار همین صفحه ببینید و پیش از معامله با فروشنده هماهنگ کنید.`;
    const change = hasData
        ? `${changeSentence(s, c.spanLabel)} کمترین قیمت ثبت‌شده ${money(s.min)} (${jalaliLabel(s.minDay)}) و بیشترین ${money(s.max)} (${jalaliLabel(s.maxDay)}) بوده است؛ میانگین قیمت پایانی روزها ${money(s.average)}.`
        : 'هنوز داده‌ی کافی برای نمایش روند ثبت نشده است؛ زرینه قیمت را هر روز ثبت می‌کند و با هر روز تازه، روند کامل‌تر می‌شود.';
    const since = c.sinceIso
        ? `تاریخچه‌ی این صفحه از ${jalaliLabel(c.sinceIso)} در همین سامانه ثبت شده است؛ پیش از آن دادهای نداریم و عددی حدس نمی‌زنیم.`
        : 'تاریخچه از اولین روز ثبت قیمت زنده در همین سامانه شروع می‌شود.';
    return [
        { q: `قیمت ${c.title} امروز چند است؟`, a: today },
        { q: `قیمت ${c.title} در ${c.spanLabel} گذشته چقدر تغییر کرده است؟`, a: change },
        {
            q: `قیمت ${c.title} فردا چند می‌شود؟`,
            a: 'ما قیمت آینده را پیش‌بینی نمی‌کنیم؛ این صفحه فقط روند ثبت‌شده‌ی گذشته را نشان می‌دهد و توصیه‌ی خرید یا فروش نیست. قیمت بازار از نرخ جهانی، نرخ ارز و عرضه و تقاضا اثر می‌پذیرد.',
        },
        {
            q: `داده‌های این صفحه از کجا می‌آید و از کی ثبت شده است؟`,
            a: `قیمت از منابع قیمت‌دهی خارجی دریافت و پیش از ثبت اعتبارسنجی می‌شود (هم‌خوانی دو منبع، نسبت‌های معقول و تازگی زمان). ${since} قیمت روزانه: اولین، بالاترین، پایین‌ترین و آخرین قیمت هر روز به وقت تهران.`,
        },
        {
            q: `قیمت نهایی خرید جواهر با این قیمت چطور حساب می‌شود؟`,
            a: `قیمت ${c.title} فقط یک جزء قیمت جواهر است؛ اجرت ساخت، سود فروشنده و مالیات هم اضافه می‌شود و مالیات فقط روی اجرت و سود حساب می‌شود، نه روی ارزش خود طلا. با محاسبه‌گر زرینه هر چهار جزء را جدا ببینید.`,
        },
    ];
}
